#!/usr/bin/env node
// F3: draft release notes from git log since the previous tag (or last N commits).
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const args = process.argv.slice(2);
const tagIndex = args.indexOf("--since-tag");
const outIndex = args.indexOf("--out");
const sinceTag = tagIndex >= 0 ? args[tagIndex + 1] : null;
const outFile = outIndex >= 0 ? args[outIndex + 1] : "docs/release-notes-draft.md";

function git(command) {
  return execSync(`git ${command}`, { cwd: root, encoding: "utf8" }).trim();
}

function listCommits(range) {
  const log = range
    ? git(`log ${range} --pretty=format:%s`)
    : git(`log -n 80 --pretty=format:%s`);
  return log
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
}

function classify(subject) {
  const lower = subject.toLowerCase();
  if (/^feat|^add|新增|支持/.test(lower)) return "features";
  if (/^fix|修复|fix/.test(lower)) return "fixes";
  if (/^docs|文档|readme/.test(lower)) return "docs";
  if (/^refactor|拆分|抽取|架构/.test(lower)) return "refactor";
  if (/^test|测试|check|契约/.test(lower)) return "quality";
  return "other";
}

let range = "";
if (sinceTag) {
  range = `${sinceTag}..HEAD`;
}

const subjects = listCommits(range);
const groups = { features: [], fixes: [], refactor: [], quality: [], docs: [], other: [] };
for (const subject of subjects) {
  groups[classify(subject)].push(subject);
}

const lines = [];
lines.push(`# Release Notes Draft`);
lines.push("");
lines.push(`> Generated by scripts/generate-release-notes.mjs · ${new Date().toISOString().slice(0, 10)}`);
lines.push(`> Range: ${range || "last 80 commits"}`);
lines.push("");

const sectionTitles = {
  features: "Features",
  fixes: "Fixes",
  refactor: "Refactor / Architecture",
  quality: "Quality & Checks",
  docs: "Docs",
  other: "Other",
};

for (const [key, title] of Object.entries(sectionTitles)) {
  if (groups[key].length === 0) continue;
  lines.push(`## ${title}`);
  lines.push("");
  for (const subject of groups[key]) {
    lines.push(`- ${subject}`);
  }
  lines.push("");
}

const content = lines.join("\n");
fs.mkdirSync(path.dirname(path.join(root, outFile)), { recursive: true });
fs.writeFileSync(path.join(root, outFile), content, "utf8");
console.log(`Wrote ${outFile} (${subjects.length} commits).`);
