use crate::{
    html_text, json_string, json_string_array, release_signing_configured,
    GeneratedCargoDependency, GeneratedReleaseConfig,
};

pub fn generated_main_rs(crate_name: &str) -> String {
    let crate_name = crate_name.replace('-', "_");
    format!(
        r#"#![cfg_attr(all(not(debug_assertions), windows), windows_subsystem = "windows")]

fn main() {{
    {crate_name}_lib::run()
}}
"#
    )
}

fn generated_cargo_dependency_lines(dependencies: &[GeneratedCargoDependency]) -> String {
    dependencies
        .iter()
        .map(|dependency| {
            if dependency.features.is_empty() {
                format!("{} = {}", dependency.name, json_string(&dependency.version))
            } else {
                format!(
                    "{} = {{ version = {}, features = {} }}",
                    dependency.name,
                    json_string(&dependency.version),
                    json_string_array(&dependency.features)
                )
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

pub fn generated_cargo_toml(
    release: &GeneratedReleaseConfig,
    dependencies: &[GeneratedCargoDependency],
    needs_ffi_loader: bool,
) -> String {
    let lib_name = release.slug.replace('-', "_");
    let package_name = json_string(&release.slug);
    let version = json_string(&release.version);
    let managed_dependencies = generated_cargo_dependency_lines(dependencies);
    let managed_dependency_block = if managed_dependencies.is_empty() {
        String::new()
    } else {
        format!("\n{managed_dependencies}\n")
    };
    let ffi_dependency = if needs_ffi_loader {
        "libloading = \"0.8\"\n"
    } else {
        ""
    };
    format!(
        r#"[package]
name = {package_name}
version = {version}
description = "Generated by Nova UI Editor"
edition = "2021"
rust-version = "1.77.2"

[lib]
name = "{lib_name}_lib"
crate-type = ["staticlib", "cdylib", "rlib"]

[build-dependencies]
tauri-build = {{ version = "2", features = [] }}

[dependencies]
tauri = {{ version = "2", features = [] }}
serde_json = "1"
{ffi_dependency}
{managed_dependency_block}
"#
    )
}

fn generated_windows_bundle_config(release: &GeneratedReleaseConfig) -> String {
    if !release_signing_configured(release) {
        return String::new();
    }

    if release.signing_mode == "windows-certificate" {
        let thumbprint = json_string(&release.certificate_thumbprint);
        let digest_algorithm = json_string(&release.digest_algorithm);
        let timestamp_url = json_string(&release.timestamp_url);
        let tsp = release.timestamp_tsp;
        return format!(
            r#",
    "windows": {{
      "certificateThumbprint": {thumbprint},
      "digestAlgorithm": {digest_algorithm},
      "timestampUrl": {timestamp_url},
      "tsp": {tsp}
    }}"#
        );
    }

    if release.signing_mode == "custom-command" {
        let sign_command = json_string(&release.sign_command);
        return format!(
            r#",
    "windows": {{
      "signCommand": {sign_command}
    }}"#
        );
    }

    String::new()
}

pub fn generated_tauri_conf(
    release: &GeneratedReleaseConfig,
    icon_paths: &[String],
    resource_paths: &[String],
) -> String {
    let product_name = json_string(&release.app_name);
    let version = json_string(&release.version);
    let identifier = json_string(&release.identifier);
    let window_title = json_string(&release.window_title);
    let bundle_targets = json_string(&release.bundle_targets);
    let icon_paths = json_string_array(icon_paths);
    let resources_config = if resource_paths.is_empty() {
        String::new()
    } else {
        format!(
            ",\n    \"resources\": {}",
            json_string_array(resource_paths)
        )
    };
    let windows_bundle_config = generated_windows_bundle_config(release);
    let resizable = release.resizable;
    let width = release.window_width;
    let height = release.window_height;
    let min_width = release.min_window_width;
    let min_height = release.min_window_height;
    format!(
        r#"{{
  "$schema": "https://schema.tauri.app/config/2",
  "productName": {product_name},
  "version": {version},
  "identifier": {identifier},
  "build": {{
    "beforeBuildCommand": "npm run build",
    "devUrl": "http://127.0.0.1:1420",
    "frontendDist": "../dist"
  }},
  "app": {{
    "windows": [
      {{
        "title": {window_title},
        "width": {width},
        "height": {height},
        "minWidth": {min_width},
        "minHeight": {min_height},
        "resizable": {resizable}
      }}
    ],
    "security": {{
      "csp": null
    }}
  }},
  "bundle": {{
    "active": true,
    "targets": {bundle_targets},
    "icon": {icon_paths}{resources_config}{windows_bundle_config}
  }}
}}
"#
    )
}

